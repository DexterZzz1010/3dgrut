"""
COLMAP Multi-Lights Dataset

A dataset class that inherits from ColmapDataset and adds support for loading
IBL (Image-Based Lighting) tensors for relighting applications.

This dataset is designed to work with multi-lights datasets generated by
the generate_multilights_dataset.py script, which creates relighted versions
of COLMAP images using different environment maps.
"""

import os
import json
import torch
import numpy as np
from PIL import Image
from pathlib import Path
from typing import Optional, List, Dict, Any
import cv2

from .dataset_colmap import ColmapDataset


class ColmapMultiLightsDataset(ColmapDataset):
    """
    COLMAP dataset with multi-lighting support.
    
    This dataset inherits from ColmapDataset and adds the ability to load
    IBL environment maps and their corresponding relit images.
    
    The dataset expects a specific directory structure:
    - images/ or images_N/: Original COLMAP images (N indicates downsample factor)
    - relit_images/: Organized by version (v001, v002, etc.)
    - ibls/: IBL environment map files
    - sparse/: COLMAP sparse reconstruction data
    - dataset_info.json: Metadata about the dataset
    """
    
    def __init__(
        self,
        config,
        device="cuda",
        split="train",
        ray_jitter=None,
        ibl_resolution=(256, 512),  # (height, width) for IBL processing
        use_original_images=True,   # If True, loads original images; if False, loads relit images
        selected_ibl_names=None,    # List of IBL names to use (None = use all)
        ibl_format="latlong",       # Format for IBL processing: "latlong", "cubemap"
    ):
        """
        Initialize the ColmapMultiLightsDataset.
        
        Args:
            config: Dataset configuration
            device: Device to load tensors on
            split: Dataset split (train/val/test)
            ray_jitter: Ray jittering for training
            ibl_resolution: Resolution for IBL processing (height, width)
            use_original_images: Whether to use original or relit images
            selected_ibl_names: List of specific IBL names to use (None = all)
            ibl_format: Format for IBL tensor representation
        """
        # Initialize parent COLMAP dataset
        super().__init__(config, device, split, ray_jitter)
        
        self.ibl_resolution = ibl_resolution
        self.use_original_images = use_original_images
        self.selected_ibl_names = selected_ibl_names
        self.ibl_format = ibl_format
        
        # Enable OpenEXR support for HDR files
        os.environ['OPENCV_IO_ENABLE_OPENEXR'] = '1'
        
        # Load multi-lights dataset metadata
        self._load_multilights_metadata()
        
        # Load IBL data
        self._load_ibl_data()
        
        # If not using original images, update image paths to relit versions
        if not use_original_images:
            self._update_image_paths_for_relighting()
    
    def get_images_folder(self):
        """
        Override parent method to use the correct image directory from metadata.
        
        Returns:
            str: Image directory name (e.g., "images", "images_2", "images_4")
        """
        # Get directory name from metadata if available
        if hasattr(self, 'multilights_metadata') and 'images_directory' in self.multilights_metadata:
            return self.multilights_metadata['images_directory']
        
        # Fallback to parent implementation
        return super().get_images_folder()
    
    def _load_multilights_metadata(self):
        """Load metadata about the multi-lights dataset."""
        metadata_path = Path(self.path) / "dataset_info.json"
        
        if not metadata_path.exists():
            raise ValueError(
                f"Multi-lights dataset metadata not found: {metadata_path}\n"
                "Make sure this dataset was generated using generate_multilights_dataset.py"
            )
        
        with open(metadata_path, 'r') as f:
            self.multilights_metadata = json.load(f)
        
        # Validate dataset type
        expected_types = ["multi_lights_colmap", "multi_lights_colmap_random"]  # Support both types
        if self.multilights_metadata.get("type") not in expected_types:
            raise ValueError(
                f"Invalid dataset type: {self.multilights_metadata.get('type')}\n"
                f"Expected one of: {expected_types}"
            )
        
        # Extract IBL information
        self.available_ibls = self.multilights_metadata["ibls"]
        self.ibl_names = [ibl["name"] for ibl in self.available_ibls]
        
        # Filter IBLs if specific ones are selected
        if self.selected_ibl_names is not None:
            filtered_ibls = []
            for ibl in self.available_ibls:
                if ibl["name"] in self.selected_ibl_names:
                    filtered_ibls.append(ibl)
            
            if not filtered_ibls:
                raise ValueError(
                    f"None of the selected IBLs found: {self.selected_ibl_names}\n"
                    f"Available IBLs: {self.ibl_names}"
                )
            
            self.available_ibls = filtered_ibls
            self.ibl_names = [ibl["name"] for ibl in self.available_ibls]
        
        print(f"Loaded multi-lights dataset with {len(self.available_ibls)} IBLs: {self.ibl_names}")
    
    def _load_ibl_data(self):
        """Load and process IBL environment maps."""
        self.ibl_tensors = {}
        dataset_root = Path(self.path)
        
        for ibl_info in self.available_ibls:
            ibl_name = ibl_info["name"]
            ibl_file_path = dataset_root / ibl_info["path"]
            
            if not ibl_file_path.exists():
                raise ValueError(f"IBL file not found: {ibl_file_path}")
            
            # Load IBL file
            try:
                ibl_tensor = self._load_and_process_ibl(ibl_file_path)
                self.ibl_tensors[ibl_name] = ibl_tensor
                print(f"Loaded IBL '{ibl_name}': {ibl_tensor.shape}")
            except Exception as e:
                raise ValueError(f"Failed to load IBL '{ibl_name}' from {ibl_file_path}: {e}")
    
    def _load_and_process_ibl(self, ibl_path: Path) -> torch.Tensor:
        """
        Load and process an IBL file into a tensor.
        
        Args:
            ibl_path: Path to the IBL file (.hdr or .exr)
            
        Returns:
            Processed IBL tensor of shape (3, H, W) in float32
        """
        # Load HDR/EXR image
        if ibl_path.suffix.lower() in ['.hdr', '.exr']:
            # Use OpenCV for HDR/EXR files
            ibl_image = cv2.imread(str(ibl_path), cv2.IMREAD_UNCHANGED)
            if ibl_image is None:
                raise ValueError(f"Failed to load IBL image: {ibl_path}")
            
            # OpenCV loads in BGR, convert to RGB
            if len(ibl_image.shape) == 3:
                ibl_image = cv2.cvtColor(ibl_image, cv2.COLOR_BGR2RGB)
        else:
            # Use PIL for regular image formats
            with Image.open(ibl_path) as img:
                ibl_image = np.array(img.convert('RGB')).astype(np.float32) / 255.0
        
        # Ensure float32 format
        if ibl_image.dtype != np.float32:
            ibl_image = ibl_image.astype(np.float32)
        
        # Resize to target resolution
        if ibl_image.shape[:2] != self.ibl_resolution:
            ibl_image = cv2.resize(
                ibl_image, 
                (self.ibl_resolution[1], self.ibl_resolution[0]), 
                interpolation=cv2.INTER_LINEAR
            )
        
        # Convert to tensor and rearrange dimensions to (C, H, W)
        ibl_tensor = torch.from_numpy(ibl_image).permute(2, 0, 1)
        
        # Clamp values to reasonable range for HDR
        ibl_tensor = torch.clamp(ibl_tensor, 0.0, 65504.0)
        
        return ibl_tensor
    
    def _update_image_paths_for_relighting(self):
        """Update image paths to use relit images instead of original images."""
        if len(self.available_ibls) == 0:
            raise ValueError("No IBLs available for relighting")
        
        # For now, use the first IBL for relit images
        # In a more advanced implementation, you might want to cycle through IBLs
        # or choose them based on some strategy
        primary_ibl = self.available_ibls[0]
        relit_dir = Path(self.path) / "relit_images" / primary_ibl["name"]
        
        if not relit_dir.exists():
            raise ValueError(f"Relit images directory not found: {relit_dir}")
        
        # Update image paths to point to relit images
        new_image_paths = []
        for original_path in self.image_paths:
            original_name = Path(original_path).name
            relit_path = relit_dir / original_name
            
            # If exact name doesn't exist, try to find a matching relit image
            if not relit_path.exists():
                # Look for files with similar names (relit files might have different naming)
                base_name = Path(original_path).stem
                potential_files = list(relit_dir.glob(f"*{base_name}*"))
                if potential_files:
                    relit_path = potential_files[0]
                else:
                    print(f"Warning: No relit image found for {original_name}, using original")
                    relit_path = original_path
            
            new_image_paths.append(str(relit_path))
        
        self.image_paths = np.array(new_image_paths, dtype=str)
        print(f"Updated to use relit images from IBL: {primary_ibl['name']}")
    
    def get_available_ibl_names(self) -> List[str]:
        """Get list of available IBL names."""
        return self.ibl_names.copy()
    
    def get_ibl_tensor(self, ibl_name: str) -> torch.Tensor:
        """
        Get IBL tensor by name.
        
        Args:
            ibl_name: Name of the IBL
            
        Returns:
            IBL tensor of shape (3, H, W)
        """
        if ibl_name not in self.ibl_tensors:
            raise ValueError(f"IBL '{ibl_name}' not found. Available: {self.ibl_names}")
        
        return self.ibl_tensors[ibl_name]
    
    def get_random_ibl_tensor(self) -> tuple[torch.Tensor, str]:
        """
        Get a random IBL tensor and its name.
        
        Returns:
            Tuple of (IBL tensor, IBL name)
        """
        ibl_name = np.random.choice(self.ibl_names)
        return self.get_ibl_tensor(ibl_name), ibl_name
    
    def __getitem__(self, idx) -> Dict[str, Any]:
        """
        Get dataset item with IBL tensor included.
        
        Args:
            idx: Index of the item
            
        Returns:
            Dictionary with image data, pose, intrinsics, and IBL tensor
        """
        # Get the base COLMAP data
        output_dict = super().__getitem__(idx)
        
        # Add IBL data
        if len(self.available_ibls) == 1:
            # If only one IBL, always use it
            ibl_name = self.ibl_names[0]
            ibl_tensor = self.get_ibl_tensor(ibl_name)
        else:
            # If multiple IBLs, choose randomly during training or first one during validation/test
            if self.split == "train":
                ibl_tensor, ibl_name = self.get_random_ibl_tensor()
            else:
                ibl_name = self.ibl_names[0]
                ibl_tensor = self.get_ibl_tensor(ibl_name)
        
        # Move IBL tensor to device
        ibl_tensor = ibl_tensor.to(self.device)
        
        # Add IBL data to output
        output_dict.update({
            "ibl_tensor": ibl_tensor,      # Shape: (3, H, W)
            "ibl_name": ibl_name,          # String name of the IBL
            "ibl_index": self.ibl_names.index(ibl_name),  # Index of the IBL
            "available_ibls": self.ibl_names.copy(),       # List of all available IBL names
        })
        
        return output_dict
    
    def get_relit_image_path(self, idx: int, ibl_name: str) -> Optional[str]:
        """
        Get the path to a relit image for a specific index and IBL.
        
        Args:
            idx: Index of the original image
            ibl_name: Name of the IBL used for relighting
            
        Returns:
            Path to the relit image, or None if not found
        """
        if ibl_name not in self.ibl_names:
            raise ValueError(f"IBL '{ibl_name}' not available. Available: {self.ibl_names}")
        
        # Get original image name
        original_path = self.image_paths[idx]
        original_name = Path(original_path).name
        
        # Construct relit image path
        relit_dir = Path(self.path) / "relit_images" / ibl_name
        relit_path = relit_dir / original_name
        
        if relit_path.exists():
            return str(relit_path)
        
        # Try to find with different naming patterns
        base_name = Path(original_path).stem
        potential_files = list(relit_dir.glob(f"*{base_name}*"))
        if potential_files:
            return str(potential_files[0])
        
        return None
    
    def get_dataset_info(self) -> Dict[str, Any]:
        """Get information about the multi-lights dataset."""
        return {
            "type": "ColmapMultiLightsDataset",
            "base_dataset": "ColmapDataset", 
            "num_images": len(self),
            "num_ibls": len(self.available_ibls),
            "ibl_names": self.ibl_names,
            "ibl_resolution": self.ibl_resolution,
            "use_original_images": self.use_original_images,
            "split": self.split,
            "metadata": self.multilights_metadata
        }
